'use strict';

/**
 * formatter.js
 * Turns the output of compareResults() into a Markdown PR comment.
 *
 * Input (from compare-results.js):
 *   { newIssues, fixedIssues, unchangedIssues, counts }
 *
 * Each issue uses the shared 7-field schema:
 *   { ruleId, severity, message, page, element, suggestedFix, fingerprint }
 */

// Hidden marker so S1's PR comment code can find and update
// the existing AccessLint comment instead of posting a new one each run.
const COMMENT_MARKER = '<!-- accesslint-report -->';

const SEVERITY_BADGES = {
  critical: '🔴 Critical',
  serious: '🟠 Serious',
  moderate: '🟡 Moderate',
  minor: '🔵 Minor',
};

const MAX_NEW_ROWS = 50;
const MAX_LIST_ROWS = 25;
const MAX_COMMENT_LENGTH = 60000; // GitHub's limit is 65536 characters

function badge(severity) {
  return SEVERITY_BADGES[severity] || `⚪ ${severity || 'Unknown'}`;
}

/** Make text safe inside a Markdown table cell. */
function cell(value) {
  return String(value === undefined || value === null ? '' : value)
    .replace(/\r?\n/g, ' ')
    .replace(/\|/g, '\\|')
    .trim();
}

/** Wrap text in an inline code span, safe for table cells. */
function code(value) {
  const text = cell(value).replace(/`/g, "'");
  return text ? `\`${text}\`` : '';
}

function pluralize(count, word) {
  return `${count} ${word}${count === 1 ? '' : 's'}`;
}

/**
 * Build a Markdown table of issues.
 * @param {Array} issues
 * @param {number} limit - max rows to show
 */
function formatIssueTable(issues, limit) {
  if (!issues || issues.length === 0) {
    return '';
  }

  const shown = issues.slice(0, limit);
  const lines = [
    '| Severity | Rule | Page | Element | Suggested fix |',
    '| --- | --- | --- | --- | --- |',
  ];

  for (const issue of shown) {
    lines.push(
      `| ${badge(issue.severity)} | ${code(issue.ruleId)} | ${code(
        issue.page
      )} | ${code(issue.element)} | ${cell(issue.suggestedFix)} |`
    );
  }

  const hidden = issues.length - shown.length;
  if (hidden > 0) {
    lines.push('');
    lines.push(`_…and ${pluralize(hidden, 'more issue')} not shown._`);
  }

  return lines.join('\n');
}

/** Wrap content in a collapsible <details> block. */
function collapsible(title, body) {
  return `<details>\n<summary>${title}</summary>\n\n${body}\n\n</details>`;
}

/**
 * Build the full Markdown comment.
 *
 * @param {object} comparison - result of compareResults()
 * @param {object} [options]
 * @param {string} [options.summary] - headline text from summary.js (optional)
 * @returns {string} Markdown
 */
function formatReport(comparison, options = {}) {
  const safe = comparison || {};
  const newIssues = safe.newIssues || [];
  const fixedIssues = safe.fixedIssues || [];
  const unchangedIssues = safe.unchangedIssues || [];

  const parts = [COMMENT_MARKER, '## ♿ AccessLint Report', ''];

  if (options.summary) {
    parts.push(options.summary, '');
  }

  // New issues (regressions): the main thing reviewers care about
  if (newIssues.length > 0) {
    parts.push(
      `### ❌ New accessibility issues (${newIssues.length})`,
      '',
      'These issues were introduced by this pull request:',
      '',
      formatIssueTable(newIssues, MAX_NEW_ROWS),
      ''
    );
  } else {
    parts.push(
      '### ✅ No new accessibility issues',
      '',
      'This pull request did not introduce any new accessibility violations.',
      ''
    );
  }

  // Fixed issues (improvements)
  if (fixedIssues.length > 0) {
    parts.push(
      collapsible(
        `🎉 Fixed issues (${fixedIssues.length})`,
        formatIssueTable(fixedIssues, MAX_LIST_ROWS)
      ),
      ''
    );
  }

  // Unchanged issues (existing debt)
  if (unchangedIssues.length > 0) {
    parts.push(
      collapsible(
        `📋 Existing issues not changed by this PR (${unchangedIssues.length})`,
        formatIssueTable(unchangedIssues, MAX_LIST_ROWS)
      ),
      ''
    );
  }

  parts.push('---', '_Generated by AccessLint (Team Ignite)_');

  let markdown = parts.join('\n');

  // Safety net so the GitHub API never rejects the comment as too long
  if (markdown.length > MAX_COMMENT_LENGTH) {
    markdown =
      markdown.slice(0, MAX_COMMENT_LENGTH) +
      '\n\n_…report truncated because it was too long._';
  }

  return markdown;
}

module.exports = { formatReport, formatIssueTable, COMMENT_MARKER };